import assert from 'node:assert/strict'
import { _electron } from 'playwright'
import { createServer } from 'node:http'
import { createHash } from 'node:crypto'
import { mkdir, mkdtemp, readFile, writeFile, rm } from 'node:fs/promises'
import path from 'node:path'
import { getAcceptanceBook, getAcceptancePdf } from '../scripts/acceptance-book.mjs'

await mkdir('.test-data', { recursive: true })
const directory = await mkdtemp(path.resolve('.test-data/reader-motion-'))
const bytes = await readFile(await getAcceptanceBook())
const pdf = await readFile(await getAcceptancePdf())
const hash = createHash('sha256').update(bytes).digest('hex')
const server = createServer((request, response) => response.writeHead(200, { 'Content-Type': request.url.endsWith('.pdf') ? 'application/pdf' : 'application/epub+zip' }).end(request.url.endsWith('.pdf') ? pdf : bytes))
await new Promise(resolve => server.listen(0, '127.0.0.1', resolve))
const application = await _electron.launch({ args: ['.'], env: { ...process.env, KINDLESPOUSE_TEST_MODE: '1', KINDLESPOUSE_TEST_NATIVE_STARTUP: '1', KINDLESPOUSE_DATA_DIR: directory }, timeout: 45000 })
const page = await application.firstWindow()
const errors = []
page.on('pageerror', error => errors.push(error.message))
const state = () => page.evaluate(() => window.kindlespouse.state())
const ready = expected => page.waitForFunction(number => {
  const card = document.querySelector('.reading-shell .reader-card')
  const image = card?.querySelector('.native-reader-page')
  return card?.getAttribute('aria-busy') === 'false' && image?.complete && image.naturalWidth === 1860 && (!number || image.alt.startsWith(`KOReader 第 ${number} 页`)) && document.querySelector('.reading-shell')?.dataset.readerReady === 'true'
}, expected, { timeout: 150000 })
const picture = () => page.locator('.reading-shell .native-reader-page')
const next = () => page.getByRole('button', { name: '下一页', exact: true })
const previous = () => page.getByRole('button', { name: '上一页', exact: true })
const origin = `http://127.0.0.1:${server.address().port}`
try {
  await page.getByRole('heading', { name: '书库', exact: true }).waitFor()
  await application.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(1440, 1000))
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.evaluate(() => window.kindlespouse.saveSettings({ readerEngine: 'koreader' }))
  await page.evaluate(url => window.kindlespouse.download(url), origin + '/Guide.epub')
  await ready(1)
  const id = (await state()).candidates[0].id
  const session = await page.locator('.reading-shell .reader-card').getAttribute('data-session-id')
  const original = await picture().getAttribute('src')
  assert.equal(await previous().isDisabled(), true)
  await page.evaluate(() => {
    window.motionCount = 0
    new MutationObserver(records => {
      for (const record of records) if (record.attributeName === 'hidden' && !record.target.hidden) window.motionCount++
    }).observe(document.querySelector('.reading-shell .native-page-turn'), { attributes: true })
  })
  await application.evaluate(({ ipcMain }) => {
    const handler = ipcMain._invokeHandlers.get('command-koreader')
    if (!handler) throw new Error('Missing native command handler')
    ipcMain.removeHandler('command-koreader')
    ipcMain.handle('command-koreader', async (...args) => {
      await new Promise(resolve => setTimeout(resolve, 1500))
      return handler(...args)
    })
  })
  await next().click()
  assert.equal(await picture().getAttribute('src'), original)
  assert.equal(await picture().isVisible(), true)
  assert.equal(await page.locator('.reading-shell .paper-overlay').count(), 0)
  const bounds = await picture().boundingBox()
  await page.mouse.dblclick(bounds.x + bounds.width * .8, bounds.y + bounds.height * .5)
  await page.getByRole('status').filter({ hasText: '正在准备下一页' }).waitFor()
  assert.equal(await picture().getAttribute('src'), original)
  await page.waitForFunction(() => !document.querySelector('.reading-shell .native-page-turn').hidden)
  await page.waitForTimeout(165)
  await mkdir('artifacts', { recursive: true })
  await page.screenshot({ path: 'artifacts/reader-paper-turn.png' })
  await ready(2)
  assert.ok(await page.evaluate(() => window.motionCount > 0))
  assert.equal((await state()).candidates.find(book => book.id === id).sha256, hash)
  await previous().click()
  await ready(1)
  await page.getByRole('button', { name: 'Aa', exact: true }).click()
  const select = page.getByLabel('翻页效果', { exact: true })
  await select.selectOption('soft')
  await page.waitForFunction(async () => (await window.kindlespouse.state()).settings.readerPageTurn === 'soft')
  const softBefore = await page.evaluate(() => window.motionCount)
  await next().click()
  await ready(2)
  assert.ok(await page.evaluate(before => window.motionCount > before, softBefore))
  await select.selectOption('none')
  await page.waitForFunction(async () => (await window.kindlespouse.state()).settings.readerPageTurn === 'none')
  const noneBefore = await page.evaluate(() => window.motionCount)
  await previous().click()
  await ready(1)
  assert.equal(await page.evaluate(() => window.motionCount), noneBefore)
  await select.selectOption('paper')
  await page.waitForFunction(async () => (await window.kindlespouse.state()).settings.readerPageTurn === 'paper')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  const reducedBefore = await page.evaluate(() => window.motionCount)
  await next().click()
  await ready(2)
  assert.equal(await page.evaluate(() => window.motionCount), reducedBefore)
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.getByRole('button', { name: '找书', exact: true }).click()
  await page.locator('.unified-search input').fill('Reading')
  await page.keyboard.press('ArrowRight')
  assert.match(await picture().getAttribute('alt'), /^KOReader 第 2 页/)
  await page.evaluate(() => document.activeElement.blur())
  await page.keyboard.press('ArrowRight')
  await ready(3)
  const swipe = await picture().boundingBox()
  await page.mouse.move(swipe.x + swipe.width * .25, swipe.y + swipe.height * .5)
  await page.mouse.down()
  await page.mouse.move(swipe.x + swipe.width * .75, swipe.y + swipe.height * .5, { steps: 8 })
  await page.mouse.up()
  await ready(2)
  assert.equal(await page.locator('.reading-shell .reader-card').getAttribute('data-session-id'), session)
  await page.getByRole('button', { name: '我的书库', exact: true }).click()
  await page.evaluate(() => document.activeElement.blur())
  await page.keyboard.press('ArrowRight')
  assert.match(await picture().getAttribute('alt'), /^KOReader 第 2 页/)
  await page.getByRole('button', { name: '找书与试读', exact: true }).click()
  await ready(2)
  await next().click()
  await page.evaluate(url => window.kindlespouse.download(url), origin + '/Other.pdf')
  await ready(1)
  assert.match(await picture().getAttribute('alt'), /共 2 页/)
  await page.evaluate(() => document.activeElement.blur())
  await page.keyboard.press('ArrowRight')
  await ready(2)
  assert.equal(await next().isDisabled(), true)
  assert.equal((await state()).jobs.length, 0)
  assert.deepEqual(errors, [])
  await page.screenshot({ path: 'artifacts/reader-page-turn-ready.png' })
  console.log(JSON.stringify({ passed: true, retainedPageDuringSlowRender: true, noBlockingPageOverlay: true, paperAndSoftTransitions: true, instantAndReducedMotion: true, rapidClicksDoNotSkipPages: true, keyboardAndSwipe: true, typingAndHiddenReaderIgnored: true, bookSwitchCancelsOldFrame: true, pageBoundaries: true, originalUnchanged: true, noImplicitTransfer: true }))
} catch (error) {
  await writeFile('.test-data/reader-motion-error.json', JSON.stringify({ message: String(error), errors, overlays: await page.locator('.paper-overlay').allTextContents() }))
  await page.screenshot({ path: '.test-data/reader-motion-failure.png' })
  throw error
} finally {
  await application.close()
  await new Promise(resolve => server.close(resolve))
  await rm(directory, { recursive: true, force: true })
}
